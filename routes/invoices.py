
from datetime import date, timedelta
from decimal import Decimal, InvalidOperation
from uuid import uuid4

from flask import Blueprint, request, jsonify
from sqlalchemy.exc import IntegrityError

from extensions import db
from models import (
    Invoice,
    InvoiceLine,
    Subscription,
    SubscriptionLine,
    User,
    Tax,
    Product
)

from services.billing_service import (
    money,
    calculate_invoice_totals
)

from services.discount_service import calculate_discount


invoices_bp = Blueprint(
    "invoices",
    __name__,
    url_prefix="/api/invoices"
)


def refresh_invoice_status(invoice):
    """Update overdue and payment status without overriding cancelled invoices."""
    if invoice.status == "cancelled":
        return

    total = money(invoice.total or 0)
    amount_paid = money(invoice.amount_paid or 0)

    if amount_paid >= total:
        invoice.status = "paid"
    elif amount_paid > 0:
        invoice.status = "partially_paid"
    elif invoice.due_date and invoice.due_date < date.today():
        invoice.status = "overdue"
    else:
        invoice.status = "unpaid"


def serialize_invoice(invoice):
    lines = InvoiceLine.query.filter_by(
        invoice_id=invoice.id
    ).all()

    customer = db.session.get(User, invoice.customer_id)

    return {
        "id": invoice.id,
        "invoice_number": invoice.invoice_number,
        "subscription_id": invoice.subscription_id,
        "customer_id": invoice.customer_id,
        "customer_name": customer.full_name if customer else None,
        "customer_email": customer.email if customer else None,
        "issue_date": invoice.issue_date.isoformat()
        if invoice.issue_date else None,
        "due_date": invoice.due_date.isoformat()
        if invoice.due_date else None,
        "subtotal": float(invoice.subtotal or 0),
        "tax_total": float(invoice.tax_total or 0),
        "discount_total": float(invoice.discount_total or 0),
        "total": float(invoice.total or 0),
        "amount_paid": float(invoice.amount_paid or 0),
        "balance_due": float(
            money(invoice.total or 0) - money(invoice.amount_paid or 0)
        ),
        "status": invoice.status,
        "lines": [
            {
                "id": line.id,
                "product_id": line.product_id,
                "description": line.description,
                "quantity": line.quantity,
                "unit_price": float(line.unit_price),
                "tax_rate": float(line.tax_rate or 0),
                "line_total": float(line.line_total)
            }
            for line in lines
        ]
    }


@invoices_bp.route("/", methods=["POST"])
def create_invoice():
    data = request.get_json(silent=True) or {}

    subscription_id = data.get("subscription_id")

    if not subscription_id:
        return jsonify({
            "success": False,
            "message": "subscription_id is required"
        }), 400

    subscription = db.session.get(Subscription, subscription_id)

    if not subscription:
        return jsonify({
            "success": False,
            "message": "Subscription not found"
        }), 404

    customer = db.session.get(User, subscription.customer_id)

    if not customer:
        return jsonify({
            "success": False,
            "message": "Subscription customer not found"
        }), 404

    # Prevent duplicate initial invoices.
    # Renewal invoices are generated by subscription automation.
    existing_invoice = Invoice.query.filter_by(
        subscription_id=subscription.id
    ).first()

    if existing_invoice:
        return jsonify({
            "success": False,
            "message": "An invoice already exists for this subscription"
        }), 409

    try:
        issue_date = (
            date.fromisoformat(data["issue_date"])
            if data.get("issue_date")
            else date.today()
        )

        due_date = (
            date.fromisoformat(data["due_date"])
            if data.get("due_date")
            else issue_date + timedelta(
                days=subscription.payment_terms_days or 0
            )
        )

        if due_date < issue_date:
            raise ValueError("Due date cannot be before issue date")

        subscription_lines = SubscriptionLine.query.filter_by(
            subscription_id=subscription.id
        ).all()

        if not subscription_lines:
            raise ValueError("Subscription has no product lines")

        invoice_lines = []
        subtotal = Decimal("0.00")

        for line in subscription_lines:
            unit_price = money(line.unit_price)
            quantity = int(line.quantity)

            if quantity <= 0:
                raise ValueError(
                    "Product quantity must be greater than zero"
                )

            if unit_price < 0:
                raise ValueError("Unit price cannot be negative")

            product = db.session.get(Product, line.product_id)

            description = (
                product.name if product else f"Product ID {line.product_id}"
            )

            line_total = money(unit_price * quantity)
            subtotal += line_total

            invoice_lines.append({
                "product_id": line.product_id,
                "description": description,
                "quantity": quantity,
                "unit_price": unit_price,
                "line_total": line_total
            })

        subtotal = money(subtotal)

        # TAX SELECTION
        tax_id = data.get("tax_id")
        tax = None
        tax_rate = Decimal("0.00")

        if tax_id is not None:
            tax = db.session.get(Tax, tax_id)

            if not tax:
                raise ValueError("Tax not found")

            if not tax.is_active:
                raise ValueError("Selected tax is inactive")

            tax_rate = Decimal(str(tax.rate))

            if tax_rate < 0 or tax_rate > 100:
                raise ValueError("Tax rate must be between 0 and 100")

        # DISCOUNT SELECTION
        discount_id = data.get("discount_id")
        discount = None
        discount_total = Decimal("0.00")

        if discount_id is not None:
            discount, discount_total = calculate_discount(
                subtotal,
                subscription_lines,
                discount_id
            )

        elif "discount_total" in data:
            discount_total = money(data["discount_total"])

            if discount_total < 0:
                raise ValueError("Discount cannot be negative")

            if discount_total > subtotal:
                raise ValueError("Discount cannot exceed subtotal")

        # CALCULATE FINAL TOTALS
        totals = calculate_invoice_totals(
            subtotal=subtotal,
            tax_rate=tax_rate,
            discount_total=discount_total
        )

        invoice = Invoice(
            invoice_number=(
                f"INV-{issue_date:%Y%m%d}-{uuid4().hex[:8].upper()}"
            ),
            subscription_id=subscription.id,
            customer_id=customer.id,
            issue_date=issue_date,
            due_date=due_date,
            subtotal=totals["subtotal"],
            tax_total=totals["tax_total"],
            discount_total=totals["discount_total"],
            total=totals["total"],
            amount_paid=Decimal("0.00"),
            status="unpaid"
        )

        db.session.add(invoice)
        db.session.flush()

        for line_data in invoice_lines:
            db.session.add(InvoiceLine(
                invoice_id=invoice.id,
                product_id=line_data["product_id"],
                description=line_data["description"],
                quantity=line_data["quantity"],
                unit_price=line_data["unit_price"],
                tax_rate=tax_rate,
                line_total=line_data["line_total"]
            ))

        if discount:
            discount.used_count += 1

        db.session.commit()

        return jsonify({
            "success": True,
            "message": "Invoice created successfully",
            "invoice": serialize_invoice(invoice)
        }), 201

    except (ValueError, TypeError, InvalidOperation, KeyError) as error:
        db.session.rollback()
        return jsonify({
            "success": False,
            "message": str(error)
        }), 400

    except IntegrityError:
        db.session.rollback()
        return jsonify({
            "success": False,
            "message": "Invoice could not be created due to a database conflict"
        }), 409


@invoices_bp.route("/", methods=["GET"])
def get_invoices():
    query = Invoice.query

    status = request.args.get("status")
    customer_id = request.args.get("customer_id")
    subscription_id = request.args.get("subscription_id")

    if status:
        query = query.filter_by(status=status)

    if customer_id:
        try:
            query = query.filter_by(customer_id=int(customer_id))
        except ValueError:
            return jsonify({
                "success": False,
                "message": "customer_id must be a valid integer"
            }), 400

    if subscription_id:
        try:
            query = query.filter_by(
                subscription_id=int(subscription_id)
            )
        except ValueError:
            return jsonify({
                "success": False,
                "message": "subscription_id must be a valid integer"
            }), 400

    invoices = query.order_by(Invoice.id.desc()).all()

    for invoice in invoices:
        refresh_invoice_status(invoice)

    db.session.commit()

    return jsonify({
        "success": True,
        "count": len(invoices),
        "invoices": [
            serialize_invoice(invoice)
            for invoice in invoices
        ]
    }), 200


@invoices_bp.route("/<int:invoice_id>", methods=["GET"])
def get_invoice(invoice_id):
    invoice = db.session.get(Invoice, invoice_id)

    if not invoice:
        return jsonify({
            "success": False,
            "message": "Invoice not found"
        }), 404

    refresh_invoice_status(invoice)
    db.session.commit()

    return jsonify({
        "success": True,
        "invoice": serialize_invoice(invoice)
    }), 200


@invoices_bp.route("/<int:invoice_id>", methods=["PUT"])
def update_invoice(invoice_id):
    invoice = db.session.get(Invoice, invoice_id)

    if not invoice:
        return jsonify({
            "success": False,
            "message": "Invoice not found"
        }), 404

    data = request.get_json(silent=True) or {}

    try:
        if invoice.status == "cancelled":
            raise ValueError("Cancelled invoices cannot be updated")

        if "due_date" in data:
            due_date = date.fromisoformat(data["due_date"])

            if due_date < invoice.issue_date:
                raise ValueError("Due date cannot be before issue date")

            invoice.due_date = due_date

        if "status" in data:
            requested_status = data["status"]

            if requested_status == "cancelled":
                if money(invoice.amount_paid or 0) > 0:
                    raise ValueError(
                        "An invoice with payments cannot be cancelled"
                    )
                invoice.status = "cancelled"

            elif requested_status in (
                "unpaid",
                "paid",
                "partially_paid",
                "overdue"
            ):
                refresh_invoice_status(invoice)

                if requested_status != invoice.status:
                    raise ValueError(
                        "Invoice status is calculated from payments and due date"
                    )
            else:
                raise ValueError("Invalid invoice status")

        if invoice.status != "cancelled":
            refresh_invoice_status(invoice)

        db.session.commit()

        return jsonify({
            "success": True,
            "message": "Invoice updated successfully",
            "invoice": serialize_invoice(invoice)
        }), 200

    except (ValueError, TypeError, InvalidOperation) as error:
        db.session.rollback()
        return jsonify({
            "success": False,
            "message": str(error)
        }), 400
